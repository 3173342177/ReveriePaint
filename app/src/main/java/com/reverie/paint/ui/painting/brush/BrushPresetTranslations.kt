    /**
     * 获取指定预设的官方中文翻译，未翻译或无匹配时返回 null。
     */
    fun getChineseTranslation(presetName: String): String? {
        val clean = presetName.removeSuffix(".kpp")
        return ZH_CN_TRANSLATIONS[clean]
            ?: ZH_CN_TRANSLATIONS[clean.replace('_', ' ')]
            ?: ZH_CN_TRANSLATIONS[presetName]
    }

    /**
     * 判断当前系统/上下文语言环境是否为中文。
     */
    fun isChineseLanguage(context: Context? = null): Boolean {
        val locale = if (context != null) {
            val locales = context.resources.configuration.locales
            if (!locales.isEmpty) locales[0] else Locale.getDefault()
        } else {
            Locale.getDefault()
        }
        return locale.language.equals("zh", ignoreCase = true)
    }

    /**
     * 仅在中文环境下返回中文译名，其他语言环境返回 null。
     */
    fun getTranslatedDisplayName(context: Context?, presetName: String): String? {
        if (!isChineseLanguage(context)) return null
        return getChineseTranslation(presetName)
    }
